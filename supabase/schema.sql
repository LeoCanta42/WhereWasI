-- Search user by email or username to send friend request
CREATE OR REPLACE FUNCTION public.send_friend_request_by_identifier(identifier TEXT)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  target_user RECORD;
  current_user_id UUID := auth.uid();
  existing_friendship RECORD;
  new_friendship_id BIGINT;
BEGIN
  IF current_user_id IS NULL THEN
    RETURN jsonb_build_object('success', false, 'error', 'Non autenticato');
  END IF;

  identifier := LOWER(TRIM(identifier));

  IF identifier = '' THEN
    RETURN jsonb_build_object('success', false, 'error', 'Inserisci un nome utente o email valido');
  END IF;

  -- Find target profile
  SELECT * INTO target_user
  FROM public.profiles
  WHERE LOWER(email) = identifier OR LOWER(username) = identifier
  LIMIT 1;

  IF target_user.id IS NULL THEN
    RETURN jsonb_build_object('success', false, 'error', 'Utente non trovato');
  END IF;

  IF target_user.id = current_user_id THEN
    RETURN jsonb_build_object('success', false, 'error', 'Non puoi inviare una richiesta a te stesso');
  END IF;

  -- Check existing friendship
  SELECT * INTO existing_friendship
  FROM public.friendships
  WHERE (requester_id = current_user_id AND addressee_id = target_user.id)
     OR (requester_id = target_user.id AND addressee_id = current_user_id)
  LIMIT 1;

  IF existing_friendship.id IS NOT NULL THEN
    IF existing_friendship.status = 'accepted' THEN
      RETURN jsonb_build_object('success', false, 'error', 'Siete già amici!');
    ELSIF existing_friendship.status = 'pending' THEN
      IF existing_friendship.requester_id = current_user_id THEN
        RETURN jsonb_build_object('success', false, 'error', 'Hai già inviato una richiesta in attesa a questo utente');
      ELSE
        -- The other person already requested: automatically accept it!
        UPDATE public.friendships
        SET status = 'accepted', updated_at = NOW()
        WHERE id = existing_friendship.id;
        
        RETURN jsonb_build_object(
          'success', true,
          'message', 'Richiesta accettata! Ora siete amici.',
          'status', 'accepted',
          'friend', jsonb_build_object(
            'id', target_user.id,
            'email', target_user.email,
            'username', target_user.username,
            'display_name', target_user.display_name,
            'avatar_url', target_user.avatar_url
          )
        );
      END IF;
    ELSIF existing_friendship.status = 'declined' THEN
      -- Re-open request
      UPDATE public.friendships
      SET requester_id = current_user_id,
          addressee_id = target_user.id,
          status = 'pending',
          updated_at = NOW()
      WHERE id = existing_friendship.id;

      RETURN jsonb_build_object('success', true, 'message', 'Richiesta di amicizia inviata!', 'status', 'pending');
    END IF;
  END IF;

  -- Create fresh request
  INSERT INTO public.friendships (requester_id, addressee_id, status)
  VALUES (current_user_id, target_user.id, 'pending')
  RETURNING id INTO new_friendship_id;

  RETURN jsonb_build_object(
    'success', true,
    'message', 'Richiesta di amicizia inviata con successo!',
    'status', 'pending',
    'friendship_id', new_friendship_id
  );
END;
$$;
